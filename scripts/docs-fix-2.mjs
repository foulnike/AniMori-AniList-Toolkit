function applyEdit(text, edit) {
  if (edit.kind === 'swap') {
    const at = text.indexOf(edit.find)
    if (at < 0) return { error: 'якорь не найден' }
    if (text.indexOf(edit.find, at + 1) >= 0) return { error: 'якорь встречается дважды' }
    return { text: text.slice(0, at) + edit.to + text.slice(at + edit.find.length) }
  }

  if (edit.kind === 'line') {
    const rows = text.split('\n')
    const hits = []
    rows.forEach((row, i) => {
      if (row.startsWith(edit.starts)) hits.push(i)
    })
    if (hits.length !== 1) return { error: `строк с таким началом: ${hits.length}` }
    rows[hits[0]] = edit.to
    return { text: rows.join('\n') }
  }

  if (edit.kind === 'all') {
    const found = text.split(edit.find).length - 1
    if (found !== edit.count) return { error: `вхождений ${found}, ждали ${edit.count}` }
    return { text: text.split(edit.find).join(edit.to) }
  }

  return { error: 'неизвестный вид правки' }
}

