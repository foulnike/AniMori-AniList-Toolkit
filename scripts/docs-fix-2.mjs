let bad = 0

for (const item of files) {
  if (!existsSync(item.file)) {
    console.error(`НЕТ ФАЙЛА ${item.file}`)
    bad++
    continue
  }

  let text = readFileSync(item.file, 'utf8')
  const errors = []

  for (const edit of item.edits) {
    const result = applyEdit(text, edit)
    if (result.error) errors.push(`    ${edit.name}: ${result.error}`)
    else text = result.text
  }

  if (errors.length > 0) {
    console.error(`НЕ ТРОНУТ ${item.file}`)
    errors.forEach((e) => console.error(e))
    bad += errors.length
    continue
  }

  writeFileSync(item.file, text, 'utf8')
  console.log(`готово ${item.file}: правок ${item.edits.length}`)
}

console.log(
  bad > 0
    ? `\nНеприменённых правок: ${bad}. Файлы с ошибками не изменены, остальные записаны.`
    : '\nВсе правки применены. Дальше: npm run format && npm run typecheck:all, потом git diff.',
)

process.exit(bad > 0 ? 1 : 0)
