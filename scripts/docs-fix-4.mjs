// Одноразовый патч: четвёртая сверка документов и комментариев с кодом.
// Запуск из корня репозитория: node scripts/docs-fix-4.mjs
//
// Каждая правка привязана к точному куску текста. Если якорь не найден
// или встречается дважды, файл не меняется вовсе: молча испорченный
// документ хуже неприменённой правки.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'

/** Склейка строк: якорь в скрипте читается так же, как лежит в файле. */
const P = (...lines) => lines.join('\n')

let bad = 0

function apply(file, edits) {
  if (!existsSync(file)) {
    console.log(`НЕ НАЙДЕН ${file}`)
    bad++
    return
  }

  const before = readFileSync(file, 'utf8')
  let text = before
  let done = 0

  for (const [name, find, to] of edits) {
    const at = text.indexOf(find)
    if (at === -1) {
      console.log(`НЕ ТРОНУТ ${file}: якорь не найден — ${name}`)
      bad++
      return
    }
    if (text.indexOf(find, at + 1) !== -1) {
      console.log(`НЕ ТРОНУТ ${file}: якорь встречается дважды — ${name}`)
      bad++
      return
    }
    text = text.slice(0, at) + to + text.slice(at + find.length)
    done++
  }

  if (text === before) {
    console.log(`без изменений ${file}`)
    return
  }

  writeFileSync(file, text)
  console.log(`готово ${file}: правок ${done}`)
}

// db.ts: инспектора журнала нет вовсе. getDbStats читает экран настроек,
// и берёт оттуда одно число — занятый объём.
