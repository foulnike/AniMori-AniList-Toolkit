// Общий слой окошка человека: карточка персонажа или автора открывается из любого
// места, а не только из состава открытого тайтла.
//
// Почему слой, а не состояние компонента: ссылку на человека может нажать описание
// тайтла, описание другого человека или полка работ. Пока окошко жило внутри
// состава людей, из описания его было не достать, а два окошка сразу спорили бы
// за Escape и за верхний слой.
//
// Собственной истории здесь нет: переходы «человек -> человек» и кнопка назад
// живут внутри самого окошка — ему виднее, кто был показан до.

import { shallowRef } from 'vue'

import type { PersonTarget } from '@/api/anilist-person'

/** Кто показан прямо сейчас. `null` — окошка нет. */
export const shownPerson = shallowRef<PersonTarget | null>(null)

/**
 * Открывает окошко человека. Зовётся и при уже открытом окошке: ссылка из
 * описания одного человека ведёт на другого, и окошко само положит прежнего
 * в свою историю.
 */
export function openPerson(target: PersonTarget): void {
  shownPerson.value = target
}

/** Закрывает окошко. */
export function closePerson(): void {
  shownPerson.value = null
}
