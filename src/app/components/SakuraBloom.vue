<script setup lang="ts">
// Подложка для круглой кнопки: в покое круг, под курсором — сакура
// с знака приложения. Ставится внутрь любого position: relative или
// absolute хозяина и сама реагирует на его :hover и :focus-visible —
// принимающей кнопке не нужно ни одного правила.
//
// ПОЧЕМУ НЕ border-radius И НЕ clip-path
//
// У сакуры между лепестками вогнутые впадины, а border-radius умеет
// только выпуклые углы: форма в принципе невыразима радиусами.
// clip-path форму бы дал, но его нельзя вешать на саму кнопку: Chromium
// режет по контуру и попадание курсора, и внешнюю обводку фокуса —
// то есть разом съел бы расширение цели нажатия до --am-touch и кольцо
// фокуса с outline-offset. Поэтому цветок — отдельный слой внутри
// кнопки с pointer-events: none, а сама кнопка остаётся прямоугольной.
//
// ПОЧЕМУ ПРОПОРЦИИ ЗНАКА РАСТЯНУТЫ
//
// Путь лепестка взят из AppMark.vue символ в символ и разворачивается
// теми же пятью поворотами вокруг (16, 16). А вот его пропорции взять
// как есть не вышло. У знака лепесток шириной 45.9 градуса в каждую
// сторону от своей оси, а шаг между осями всего 72: соседние лепестки
// захлёстываются на девять градусов, и впадина между ними сидит на
// 0.93 от наибольшего радиуса. На плите знака это читается цветком за
// счёт контраста розового с тёмно-синим, а на кнопке 28 пикселей
// такая впадина — один пиксель: вышел бы чуть неровный круг, а не
// сакура. Поэтому лепесток сжат поперёк своей оси в 0.7038 раза:
// полуширина стала ровно 36 градусов, соседние лепестки сходятся
// ровно в точку без захлёста, и впадина села на 0.74. Надрез на конце
// лепестка — тот самый, из знака, и он пережил сжатие без потерь:
// он лежит на самой оси, где сжатие по ширине ничего не меняет.
//
// ПОЧЕМУ ЛЕПЕСТКИ НЕ ПОЛУПРОЗРАЧНЫЕ
//
// Пять путей сходятся у центра и там налегают друг на друга. При
// полупрозрачной заливке каждое наложение темнеет, и по центру цветка
// выступает пятилучевая звёзда из швов. Плотная заливка этого не
// знает вообще: плотное поверх плотного — тот же цвет. Отдельность
// от постера даёт тень по силуэту, а не оправа: обводка вдоль контура
// с пятью впадинами на таком размере слипается в кашу.

/** Лепесток знака: остриём вверх, надрез в точке (16, 7). */
const PETAL =
  'M16 17.1 C12.1 16.6 9.3 13.2 9.6 9.8 C9.8 6.5 12.9 4.5 16 7 ' +
  'C19.1 4.5 22.2 6.5 22.4 9.8 C22.7 13.2 19.9 16.6 16 17.1 Z'

/** Пять поворотов по 72 градуса — ровно как в маске знака. */
const TURNS = [0, 72, 144, 216, 288]

// 1.7467 — вывод наибольшего радиуса лепестка на 18 единиц (он равен
// 10.305 после сжатия), 1.2291 — то же число, умноженное на сжатие
// 0.7038 по ширине. Оба translate нужны, чтобы scale шёл от центра
// квадрата, а не от его левого верхнего угла.
const petalTurn = (turn: number) =>
  `rotate(${turn} 16 16) translate(16 16) scale(1.2291 1.7467) translate(-16 -16)`
</script>

<template>
  <svg class="am-bloom" viewBox="0 0 32 32" aria-hidden="true" focusable="false">
    <circle class="am-bloom__bud" cx="16" cy="16" r="14" />
    <g class="am-bloom__petals">
      <path v-for="turn in TURNS" :key="turn" :d="PETAL" :transform="petalTurn(turn)" />
    </g>
  </svg>
</template>

<!-- Стили нарочно без scoped: цветок должен сам видеть :hover своего
     хозяина, а из scoped блока до родителя не дотянуться: пришлось бы
     держать правила в каждой кнопке через :deep(), то есть размазать
     одну анимацию по всем местам внедрения. Имена под префиксом
     am-bloom заняты только здесь. -->
<style>
.am-bloom {
  /* Нависание за край кнопки: лепестки раскрываются шире круга,
     иначе цветок не распускается, а втягивается внутрь себя.
     Считается от размера хозяина: 2px на круг 28px — цветок 36px
     в распуске, потому что сами лепестки выходят за viewBox. */
  position: absolute;
  inset: calc(-1 * var(--am-bloom-out, 2px));

  /* Клики и наведение остаются у кнопки: иначе курсор попадал бы
     на выступающий лепесток и терял его вместе с распуском. */
  pointer-events: none;

  /* Лепестки доходят до радиуса 18 в квадрате 32 — две единицы
     наружу. Без этого концы срезало внешним svg. */
  overflow: visible;

  filter: drop-shadow(0 2px 5px var(--am-veil));
  transition: filter var(--am-mid) var(--am-ease);
}

/* Круг в покое. Под курсором съёживается до сердцевины: оставь его
   в полный рост — он заполнит впадины и цветок снова станет кругом. */
.am-bloom__bud {
  fill: var(--am-bloom-deep, #0b1017);
  transform-box: view-box;
  transform-origin: 16px 16px;
  transition:
    fill var(--am-mid) var(--am-ease),
    transform var(--am-mid) var(--am-ease);
}

/* Закручены и стянуты внутрь круга. Поворот обязателен: без него
   цветок не распускается, а наезжает на зрителя. */
.am-bloom__petals {
  fill: var(--am-bloom-petal, #0b1017);
  opacity: 0;
  transform: rotate(-26deg) scale(0.62);
  transform-box: view-box;
  transform-origin: 16px 16px;
  transition:
    fill var(--am-mid) var(--am-ease),
    opacity var(--am-mid) var(--am-ease),
    transform var(--am-mid) var(--am-ease);
}

/* Хозяин описан через :where, чтобы правило не перевешивало собственные
   стили кнопки: вес селектора остаётся как у одного класса. */
:where(button, a, [role='button']):hover > .am-bloom .am-bloom__petals,
:where(button, a, [role='button']):focus-visible > .am-bloom .am-bloom__petals {
  opacity: 1;
  transform: none;
}

:where(button, a, [role='button']):hover > .am-bloom .am-bloom__bud,
:where(button, a, [role='button']):focus-visible > .am-bloom .am-bloom__bud {
  transform: scale(0.93);
}

/* Свечение розовым, а не заливка розовым во всю силу: на чистом
   #f5b3c8 белый крестик даёт контраст 1.7:1 и исчезает. */
:where(button, a, [role='button']):hover > .am-bloom,
:where(button, a, [role='button']):focus-visible > .am-bloom {
  filter: drop-shadow(0 2px 5px var(--am-veil))
    drop-shadow(0 0 9px rgb(var(--am-sakura-rgb) / 0.45));
}

/* В покое лепестки не крутятся и не растут: остаётся просто
   появление, а общее правило темы гасит его длительность. */
@media (prefers-reduced-motion: reduce) {
  .am-bloom__petals {
    transform: none;
  }
}
</style>
