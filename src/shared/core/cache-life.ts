// Сроки хранения складских записей и разброс, чтобы они не истекали залпом.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ
// Срок хранения — это решение о том, как часто мы беспокоим чужой сервер,
// и держать его россыпью по модулям значит не иметь его вовсе. Здесь он один
// на всех и виден целиком: файл отвечает на вопрос «почему программа спросила
// это во второй раз» одним взглядом, а не обходом десяти модулей.
//
// РАЗБРОС СЧИТАЕТСЯ ОТ КЛЮЧА, А НЕ СЛУЧАЙНО
// Пятьсот записей, легших на склад за одну прокрутку, истекли бы в одну минуту
// и дали бы залп из пятисот запросов — ровно то, от чего мы уходим. Разброс
// ±20 % разносит их во времени. Случайное число здесь не годится: оно давало бы
// разный ответ на каждое чтение, и одна и та же запись оказывалась бы то
// свежей, то просроченной. Множитель выводится из самого ключа: он постоянен,
// пока постоянен ключ, и при этом у соседних записей разный.
//
// БЕССРОЧНОЕ — ЭТО ТОЖЕ СРОК
// Состав персонажей и жанры тайтла не меняются, и спрашивать их повторно не
// нужно никогда. Такие записи помечаются LIFE_FOREVER, а не сроком в сто лет:
// сто лет — это забытое решение, а бесконечность — решение названное.

/** Минута, час и сутки в миллисекундах: сроки ниже читаются словами, а не числами. */
export const MINUTE_MS = 60_000
export const HOUR_MS = 3_600_000
export const DAY_MS = 86_400_000

/** Бессрочно: запись верна, пока её не снесут вручную из настроек. */
export const LIFE_FOREVER = Number.POSITIVE_INFINITY

/**
 * Карточка завершённого тайтла: неделя. Меняться там может только средняя
 * оценка, и та на сотые доли.
 */
export const LIFE_CARD_FINISHED = 7 * DAY_MS

/**
 * Карточка идущего тайтла: сутки. Серии выходят раз в неделю, но номер
 * ближайшей серии и счёт вышедшего должны обновляться заметно чаще срока
 * самого выхода, иначе карточка неделю обещает вчерашнюю серию.
 */
export const LIFE_CARD_AIRING = DAY_MS

/** Персонажи и авторы: состав снят с готового тайтла и уже не изменится. */
export const LIFE_PEOPLE = LIFE_FOREVER

/** Справочник тэгов каталога: около тысячи семисот строк, новые появляются раз в месяцы. */
export const LIFE_TAGS = 30 * DAY_MS

/** Жанры тайтла: заданы при выпуске и не правятся. */
export const LIFE_GENRES = LIFE_FOREVER

/** Полка «Сейчас выходит»: сезон меняется четыре раза в год, состав — реже суток. */
export const LIFE_SHELF_AIRING = 6 * HOUR_MS

/** Полка «В тренде»: единственная, где смысл в самой свежести. */
export const LIFE_SHELF_TRENDING = 2 * HOUR_MS

/** Полка «Лучшее»: список верхних оценок за сутки не сдвигается. */
export const LIFE_SHELF_TOP = DAY_MS

/** Полка по жанрам: тот же порядок по оценке, что и «Лучшее», только суженный. */
export const LIFE_SHELF_GENRE = DAY_MS

/** Советы «по мотивам»: голоса за связи набираются месяцами. */
export const LIFE_RECS = DAY_MS

/**
 * Выдача поиска и страница ленты: четверть часа в памяти запуска.
 * На склад это не ложится сознательно — слов и отборов бесконечно много,
 * и склад забился бы одноразовыми записями.
 */
export const LIFE_SEARCH = 15 * MINUTE_MS
export const LIFE_FEED = 15 * MINUTE_MS

/**
 * Метка доступности, ответ «да»: неделя. Вход к тайтлу пропадает разве что
 * вместе со самой службой, а вопрос о нём стоит запроса на плитку.
 */
export const LIFE_PLAY_YES = 7 * DAY_MS

/**
 * Тот же ответ, но «нет», у идущего тайтла: сутки. Сегодня озвучки нет,
 * а к следующей серии она есть, и держать отказ дольше значит весь срок
 * врать человеку про живой тайтл.
 */
export const LIFE_PLAY_NO_AIRING = DAY_MS

/**
 * «Нет» у завершённого тайтла: две недели. Кого не взяли за годы, не возьмут
 * и до следующей проверки, а суточный срок гнал в сеть всю сетку старых
 * тайтлов заново каждый день.
 */
export const LIFE_PLAY_NO_FINISHED = 14 * DAY_MS

/**
 * Озвучки Kodik и адреса страниц серий у идущего тайтла: сутки. Сами адреса
 * постоянны — меняется состав серий, и раз в неделю он прирастает новой.
 */
export const LIFE_VOICES_AIRING = DAY_MS

/** То же у завершённого тайтла: неделя. Новых серий там уже не будет. */
export const LIFE_VOICES_FINISHED = 7 * DAY_MS

/** Соответствие «наш тайтл → релиз Aniliberty»: номер релиза за ним закреплён. */
export const LIFE_ALIB_MATCH = LIFE_FOREVER

/** Промах поиска Aniliberty: сутки. Релиз мог выйти вчера. */
export const LIFE_ALIB_MISS = DAY_MS

/**
 * Отказ по человеку: неделя. Русского имени у Шикимори к вечеру не появится,
 * а вот к следующему выпуску датасета — вполне.
 */
export const LIFE_PERSON_MISS = 7 * DAY_MS

/** Насколько срок гуляет в обе стороны. Двадцать процентов от самого срока. */
const SPREAD = 0.2

/**
 * Множитель срока для ключа: постоянное число из диапазона 0,8…1,2.
 *
 * Свёртка простая нарочно: это не защита и не хеш для сравнения, а способ
 * получить из строки одно устойчивое число. Умножение с остатком держит
 * значение в границах точного целого, так что результат одинаков всегда
 * и везде.
 */
function spreadFactor(key: string): number {
  let hash = 0
  for (let i = 0; i < key.length; i++) {
    hash = (hash * 31 + key.charCodeAt(i)) % 100_000_007
  }

  const steps = Math.round(SPREAD * 200) + 1
  const shift = (hash % steps) / 100 - SPREAD
  return 1 + shift
}

/**
 * Свежа ли складская запись. Ключ участвует ради разброса: у двух записей,
 * легших рядом, сроки истекут в разные часы.
 *
 * Запись из будущего считается свежей: часы могли переставить назад, а выбросить
 * из-за этого весь склад — худший из возможных ответов на неверное время.
 */
export function isFresh(key: string, ts: number | null | undefined, life: number): boolean {
  if (typeof ts !== 'number' || ts <= 0) return false
  if (!Number.isFinite(life)) return true

  const age = Date.now() - ts
  if (age < 0) return true

  return age < life * spreadFactor(key)
}

/**
 * Свежа ли запись в памяти запуска. Разброса здесь нет: память живёт до
 * закрытия программы, и залпа после её истечения быть не может — к тому
 * времени спрашивать будет уже некому.
 */
export function isFreshAt(at: number | null | undefined, life: number): boolean {
  if (typeof at !== 'number' || at <= 0) return false
  if (!Number.isFinite(life)) return true

  const age = Date.now() - at
  return age < 0 || age < life
}
