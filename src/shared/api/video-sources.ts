// Сборка реестра источников видео: единственное место, где перечислены резолверы.
//
// Ядро (core/video.ts) знает только форму источника и держит пустой реестр.
// Имена живут здесь: зависимости в проекте направлены в одну сторону, api → core.
//
// Порядок вызовов здесь — это и порядок перебора на экране: сначала открытый
// API без подписей и без сроков, и только потом цепочки, которые приходится раскручивать.

import { registerVideoSource } from '../core/video'
import { anilibertySource } from './aniliberty'

/** Реестр общий на весь запуск, поэтому сборка идёт ровно один раз. */
let done = false

/**
 * Складывает источники в реестр. Зовётся перед первым обращением к плееру;
 * повторный вызов ничего не стоит и ничего не ломает.
 */
export function setupVideoSources(): void {
  if (done) return

  registerVideoSource(anilibertySource)

  done = true
}
